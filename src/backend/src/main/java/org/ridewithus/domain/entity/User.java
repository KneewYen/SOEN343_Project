package org.ridewithus.domain.entity;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Column;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.Setter;

@Setter
@Getter
@Entity
@Table(name = "users")
@AllArgsConstructor
public class User {
    
    @Id //primary key 
    @GeneratedValue(strategy = GenerationType.IDENTITY) //value is generated by Database, not through constructors
    private Long id;

    private String fullName;
    private String userName;
    private String address;
    private String email;  
    private String role = "rider"; //user are automatically user unless specified otherwise
    private String password ;


    @Column(name = "flex_dollar_balance", nullable = false)
    private int flex_dollar_balance = 0 ;

    // convenience helpers for working with flex dollars
    public int getFlexDollars() {
        return flex_dollar_balance;
    }

    public void setFlexDollars(int flexDollars) {
        this.flex_dollar_balance = flexDollars;
    }

    /**
     * Apply (deduct) flex dollars from the user's balance.
     * Will not go below zero.
     * @param amount the amount to deduct
     * @return the amount actually deducted
     */

    //ADD PAYMENT INFO OR CREATE A NEW TABLE??
    @ManyToOne
    @JoinColumn(name = "pricing_plan_id", nullable = true)
    private PricingPlan pricingPlan;

    public User() {}

    public User(String fullname, String userName, String address, String email, String password){
        this.fullName = fullname ;
        this.userName = userName ;
        this.address = address ;
        this.email = email ;
        this.password = password ;
        this.role = "rider" ;  //ensures user is a rides
    }

    // when manually entering users, use this one to allow operator role
    public User(String fullname, String userName, String address, String email, String role, String password){
        this.fullName = fullname ;
        this.userName = userName ;
        this.address = address ;
        this.email = email ;
        this.password = password ;
        this.role = role ; 
    }

    // Setters
    public void setFullName(String name){
        this.fullName = name;
    }
    public void setUserName(String username){
        this.userName = username;
    }
    public void setAddress(String address){
        this.address = address;
    }
    public void setEmail(String email){
        this.email = email;
    }
    public void setPassword(String password){
        this.password = password;
    }
    public void setRole(String role){
        this.role = role;
    }
    public void setPricingPlan(PricingPlan plan){
        this.pricingPlan = plan;
    }
}
